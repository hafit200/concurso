    private void btnGuardarEntrenadorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarEntrenadorActionPerformed
        System.out.println("BOTON GUARDAR PRESIONADO");

        Entrenador entrenador = new Entrenador();

        entrenador.setNombre(txtNombreEntrenador.getText());
        entrenador.setCorreo(txtCorreoEntrenador.getText());
        entrenador.setPassword(txtPasswordEntrenador.getText());
        entrenador.setEstado("ACTIVO");
        entrenador.setRolEstrategico(txtRolEstrategico.getText());

        entrenador.setAnosExperiencia(
                Integer.parseInt(txtAnosExperiencia.getText())
        );

        boolean guardado = entrenadorControlador.insertar(entrenador);

        if (guardado) {

            JOptionPane.showMessageDialog(
                    this,
                    "Entrenador guardado"
            );

            cargarEntrenadores();
            cargarComboEntrenadores();
            limpiarEntrenador();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo guardar"
            );

        }       // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarEntrenadorActionPerformed

