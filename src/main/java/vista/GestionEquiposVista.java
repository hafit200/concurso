    public void cargarEquipos() {

        modeloEquipos.setRowCount(0);

        ArrayList<String[]> lista = equipoControlador.consultar();

        for (String[] e : lista) {

            modeloEquipos.addRow(e);
        }
    }

    public void cargarJugadores() {

        modeloJugadores.setRowCount(0);

        ArrayList<String[]> lista = jugadorControlador.consultar();

        for (String[] j : lista) {

            modeloJugadores.addRow(j);
        }
    }

    public void cargarEntrenadores() {

        modeloEntrenadores.setRowCount(0);

        ArrayList<String[]> lista = entrenadorControlador.consultar();

        for (String[] e : lista) {

            modeloEntrenadores.addRow(e);
        }
    }

    public void cargarComboEntrenadores() {

        cmbEntrenadorEquipos.removeAllItems();

        cmbEntrenadorEquipos.addItem("Sin entrenador");

        ArrayList<String[]> lista = entrenadorControlador.consultar();

        for (String[] e : lista) {

            cmbEntrenadorEquipos.addItem(
                    e[0] + " - " + e[1]
            );
        }
    }

