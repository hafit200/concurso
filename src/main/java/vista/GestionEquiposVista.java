    private void btnGuardarEquipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarEquipoActionPerformed
        Equipo equipo = new Equipo();

        equipo.setCodigoUnico(
                txtCodigoEquipo.getText()
        );

        equipo.setNombre(
                txtNombreEquipo.getText()
        );

        equipo.setPais(
                txtPaisEquipo.getText()
        );

        equipo.setFechaFundacion(
                LocalDate.parse(
                        txtFechaFundacion.getText()
                )
        );

        if (cmbEntrenadorEquipos.getSelectedIndex() == 0) {

            equipo.setEntrenador(null);

        } else {

            String dato = cmbEntrenadorEquipos
                    .getSelectedItem()
                    .toString();

            int id = Integer.parseInt(
                    dato.split(" - ")[0]
            );

            Entrenador entrenador = new Entrenador();

            entrenador.setIdUsuario(id);

            equipo.setEntrenador(entrenador);
        }

        equipoControlador.insertar(equipo);

        JOptionPane.showMessageDialog(
                this,
                "Equipo guardado"
        );

        cargarEquipos();

        limpiarEquipo();        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarEquipoActionPerformed

    private void btnEliminarEquipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarEquipoActionPerformed
        int fila = tblEquipos.getSelectedRow();

        if (fila == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un equipo"
            );

        } else {

            int id = Integer.parseInt(
                    tblEquipos.getValueAt(
                            fila,
                            0
                    ).toString()
            );

            equipoControlador.eliminar(id);

            JOptionPane.showMessageDialog(
                    this,
                    "Equipo eliminado"
            );

            cargarEquipos();
        }    // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarEquipoActionPerformed

