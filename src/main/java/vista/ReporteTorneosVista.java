    public void cargarEquipos() {

        cmbEquipo.removeAllItems();

        cmbEquipo.addItem("0 - TODOS");

        ArrayList<String[]> lista
                = equipoControlador.consultar();

        for (String[] e : lista) {

            cmbEquipo.addItem(
                    e[0] + " - " + e[2]
            );
        }
    }

    public void cargarGrafica() {

        DefaultCategoryDataset datos = new DefaultCategoryDataset();

        Map<String, Integer> conteo = new HashMap<>();

        for (int i = 0; i < tblReporte.getRowCount(); i++) {

            String torneo = tblReporte.getValueAt(i, 0).toString();

            if (conteo.containsKey(torneo)) {

                conteo.put(
                        torneo,
                        conteo.get(torneo) + 1
                );

            } else {

                conteo.put(torneo, 1);
            }
        }

        for (String torneo : conteo.keySet()) {

            datos.addValue(
                    conteo.get(torneo),
                    "Equipos",
                    torneo
            );
        }

        JFreeChart grafica = ChartFactory.createBarChart(
                "Equipos inscritos por torneo",
                "Torneo",
                "Cantidad de equipos",
                datos
        );

        ChartPanel panel = new ChartPanel(grafica);

        panel.setPreferredSize(
                new java.awt.Dimension(500, 250)
        );

        pnlGrafica.removeAll();

        pnlGrafica.setLayout(
                new java.awt.FlowLayout()
        );

        pnlGrafica.add(panel);

        pnlGrafica.revalidate();
        pnlGrafica.repaint();
    }

