    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        try {

            LocalDate fechaInicio
                    = LocalDate.parse(txtFechaInicio.getText());

            LocalDate fechaFin
                    = LocalDate.parse(txtFechaFin.getText());

            String datoEquipo
                    = cmbEquipo.getSelectedItem().toString();

            int idEquipo = Integer.parseInt(
                    datoEquipo.split(" - ")[0]
            );

            ArrayList<String[]> lista
                    = reporteControlador.generarReporte(
                            fechaInicio,
                            fechaFin,
                            idEquipo
                    );

            modeloReporte.setRowCount(0);

            for (String[] fila : lista) {

                modeloReporte.addRow(fila);
            }
            cargarGrafica();

            JOptionPane.showMessageDialog(
                    this,
                    "Reporte generado"
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Revise los datos ingresados"
            );
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnGenerarActionPerformed

